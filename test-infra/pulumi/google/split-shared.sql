SELECT CONCAT(
    FORMAT('%06d', id),
    TO_BASE64(SHA512(CONCAT('0:', CAST(id AS STRING)))),
    TO_BASE64(SHA512(CONCAT('1:', CAST(id AS STRING)))),
    TO_BASE64(SHA512(CONCAT('2:', CAST(id AS STRING)))),
    TO_BASE64(SHA512(CONCAT('3:', CAST(id AS STRING))))
) AS id
FROM UNNEST(GENERATE_ARRAY(1, 600000)) AS id
